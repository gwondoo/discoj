import assert from 'node:assert/strict';
import {VolumeGesture} from '../activity-test/src/lib/volume-gesture.ts';
const drafts=[],commits=[],discards=[];
let value;
const gesture=new VolumeGesture(v=>{value=v;drafts.push(v);},()=>commits.push(value),()=>discards.push(true));
gesture.pointerDown();
gesture.change(20);
await new Promise(resolve=>setTimeout(resolve,650));
assert.deepEqual(commits,[], 'Holding still during drag must not send volume');
gesture.change(35);gesture.blur();
assert.deepEqual(commits,[], 'Pointer capture must wait for release even if focus changes');
gesture.pointerUp();gesture.lostCapture();gesture.blur();
assert.deepEqual(commits,[35], 'Release sends final value once; lost capture after release does not cancel');
assert.equal(discards.length,0);
gesture.change(50);gesture.keyUp('ArrowRight');gesture.blur();
assert.deepEqual(commits,[35,50], 'Keyboard release commits, blur does not duplicate');
gesture.pointerDown();gesture.change(70);gesture.cancel();gesture.pointerUp();
assert.deepEqual(commits,[35,50], 'Cancelled pointer never submits');
gesture.pointerDown();gesture.change(80);gesture.lostCapture();
assert.equal(discards.length,2, 'Unexpected loss of capture discards the local draft');
console.log('Volume gesture tests passed: held drag, final release, capture, keyboard, cancellation');
