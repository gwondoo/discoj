import assert from 'node:assert/strict';
import {FreshRead} from '../activity/src/lib/fresh-read.ts';
const requests = [];
const reads = new FreshRead(() => new Promise((resolve, reject) => requests.push({resolve,reject})));
const tick = () => new Promise(resolve => setImmediate(resolve));
const beforePause = reads.run();
const poll = reads.run();
await tick();assert.equal(requests.length,1);
const afterPause = reads.run(true);
await tick();assert.equal(requests.length,1);
requests[0].resolve({state:'playing'});
assert.equal((await beforePause).state,'playing');await poll;
await tick();assert.equal(requests.length,2);
requests[1].resolve({state:'paused'});
assert.equal((await afterPause).state,'paused');
const fail=reads.run();await tick();const recover=reads.run(true);
requests[2].reject(Error('offline'));await assert.rejects(fail);
await tick();requests[3].resolve({state:'paused'});
assert.equal((await recover).state,'paused');
console.log('Fresh state tests passed: coalescing, post-control read avoids stale playing state, recovery');
